/* ─── Generic scroll reveal (no GSAP dependency) ─────────────────
   Auto-tags common content blocks so every page gets consistent
   entrance motion without hand-placing classes per page. Grid/group
   children get a --reveal-i index for a staggered cascade instead
   of landing in one flat block. */
function initReveal() {
  const alreadyTagged = el => el.classList.contains('reveal') || el.classList.contains('reveal-soft')
    || el.classList.contains('reveal-card') || el.classList.contains('reveal-quote') || el.classList.contains('no-reveal');
  document.querySelectorAll('.news-card, .step, .contact-item, .download-card, .how-to__intro, .promo-banner')
    .forEach(el => { if (!alreadyTagged(el)) el.classList.add('reveal'); });
  document.querySelectorAll('.story__panel, .product-detail__img, .confirmation__icon')
    .forEach(el => { if (!alreadyTagged(el)) el.classList.add('reveal-soft'); });
  document.querySelectorAll('.card')
    .forEach(el => { if (!alreadyTagged(el)) el.classList.add('reveal-card'); });
  document.querySelectorAll('.testimonial')
    .forEach(el => { if (!alreadyTagged(el)) el.classList.add('reveal-quote'); });

  document.querySelectorAll('.catalog__grid, .news-grid, .how-to__steps, .testimonials__grid, .promo-banners').forEach(group => {
    Array.from(group.children).forEach((child, i) => child.style.setProperty('--reveal-i', Math.min(i, 8)));
  });

  const els = document.querySelectorAll('.reveal, .reveal-soft, .reveal-card, .reveal-quote');
  if (!els.length) return;
  if (window.matchMedia('(prefers-reduced-motion: reduce)').matches) {
    els.forEach(el => el.classList.add('in'));
    return;
  }
  const io = new IntersectionObserver(entries => {
    entries.forEach(e => {
      if (e.isIntersecting) { e.target.classList.add('in'); io.unobserve(e.target); }
    });
  }, { threshold: 0.12 });
  els.forEach(el => io.observe(el));
}
document.addEventListener('DOMContentLoaded', initReveal);

/* ─── Page header parallax (interior pages) ──────────────────────
   Mirrors the home hero's scroll parallax: .page-header__bg bleeds
   ±110px past its .page-header so it can shift on scroll without
   ever showing an edge, keeping the banner from feeling like a
   frozen photo. */
function initPageHeaderParallax() {
  const bgs = Array.from(document.querySelectorAll('.page-header__bg'));
  if (!bgs.length || window.matchMedia('(prefers-reduced-motion: reduce)').matches) return;
  let ticking = false;
  const apply = () => {
    bgs.forEach(bg => {
      const header = bg.closest('.page-header');
      const offset = Math.max(-110, Math.min(110, -header.getBoundingClientRect().top * 0.4));
      bg.style.transform = `translate3d(0, ${offset}px, 0)`;
    });
    ticking = false;
  };
  window.addEventListener('scroll', () => {
    if (!ticking) { requestAnimationFrame(apply); ticking = true; }
  }, { passive: true });
  apply();
}
document.addEventListener('DOMContentLoaded', initPageHeaderParallax);
