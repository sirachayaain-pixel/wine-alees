function handleAddToCart(btn, id) {
  addToCart(id);
  if (btn.dataset.added === '1') return;
  btn.dataset.added = '1';
  btn.classList.add('card__add--added');
  btn.innerHTML = CARD_ADDED_ICON;
  setTimeout(() => {
    btn.classList.remove('card__add--added');
    btn.innerHTML = CARD_ADD_ICON;
    delete btn.dataset.added;
  }, 1200);
}

/* ─── Cart (persisted to localStorage — shared across pages) ──── */
const CART_KEY = 'alees_cart_v1';

function getCart() {
  try { return JSON.parse(localStorage.getItem(CART_KEY)) || []; }
  catch (e) { return []; }
}

function setCart(cart) {
  localStorage.setItem(CART_KEY, JSON.stringify(cart));
  updateCartBadge();
}

function addToCart(id, qty) {
  qty = qty || 1;
  const wine = WINES.find(w => w.id === id);
  if (!wine) return;
  const cart = getCart();
  const existing = cart.find(i => i.id === id);
  if (existing) existing.qty += qty;
  else cart.push({ id, qty });
  setCart(cart);
}

function updateCartQty(id, qty) {
  let cart = getCart();
  if (qty <= 0) cart = cart.filter(i => i.id !== id);
  else {
    const item = cart.find(i => i.id === id);
    if (item) item.qty = qty;
  }
  setCart(cart);
}

function removeFromCart(id) {
  setCart(getCart().filter(i => i.id !== id));
}

function cartWithDetails() {
  return getCart()
    .map(i => ({ ...WINES.find(w => w.id === i.id), qty: i.qty }))
    .filter(i => i.id);
}

function cartTotal() {
  return cartWithDetails().reduce((s, i) => s + i.price * i.qty, 0);
}

function cartCount() {
  return getCart().reduce((s, i) => s + i.qty, 0);
}

let _prevCartCount = null;
function updateCartBadge() {
  const count = cartCount();
  const grew = _prevCartCount !== null && count > _prevCartCount;
  document.querySelectorAll('.nav__cart-badge').forEach(badge => {
    badge.textContent = count;
    badge.classList.toggle('visible', count > 0);
    if (grew) {
      badge.classList.remove('pulse');
      void badge.offsetWidth; /* restart the animation on rapid successive adds */
      badge.classList.add('pulse');
    }
  });
  _prevCartCount = count;
}

document.addEventListener('DOMContentLoaded', updateCartBadge);

